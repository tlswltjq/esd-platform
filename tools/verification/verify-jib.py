#!/usr/bin/env python3
"""Verify the default Jib images in a disposable local Compose project."""

import argparse
import base64
from datetime import datetime, timezone
import json
import os
import platform
from pathlib import Path
import secrets
import shutil
import socket
import subprocess
import sys
import tempfile
import urllib.request
import uuid
import xml.etree.ElementTree as ET

from support.ports import application_offset
from support.minio_image import ensure_minio_image
from support.start_apps import copy_launcher


ROOT = Path(__file__).resolve().parents[2]
PORTS = {"auth": 8091, "gateway": 8080, "studio": 8085, "review": 8086,
         "catalog": 8081, "store": 8087, "order": 8082, "payment": 8083,
         "license": 8084, "download": 8088, "settlement": 8089, "mock-pg": 8092}


def capture(command, **kwargs):
    return subprocess.check_output(command, cwd=ROOT, text=True, **kwargs).strip()


def main():
    started_at = datetime.now(timezone.utc).isoformat()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--skip-build", action="store_true", help="Use images already generated by Gradle")
    parser.add_argument("--tracing", action="store_true", help="Include isolated Tempo/Grafana and durable tracing fault checks")
    parser.add_argument("--foundation-only", action="store_true", help="Verify common HTTP tracing before Payment context persistence")
    parser.add_argument("--prometheus-only", action="store_true", help="Verify real production scrape targets and metrics")
    parser.add_argument("--backup-restore", action="store_true",
                        help="Lose MySQL and MinIO between purchase phases and restore them from continuous copies")
    args = parser.parse_args()
    if args.prometheus_only and (args.tracing or args.foundation_only):
        parser.error("--prometheus-only cannot be combined with tracing modes")
    if args.backup_restore and (args.prometheus_only or args.tracing or args.foundation_only):
        parser.error("--backup-restore cannot be combined with other verification modes")
    if args.foundation_only:
        args.tracing = True
    scratch = os.environ.get("KIROCREW_SCRATCH")
    output_root = Path(scratch) if scratch and (args.prometheus_only or args.backup_restore) else ROOT / "runs"
    output_root.mkdir(exist_ok=True)
    prefix = "prometheus-validation-" if args.prometheus_only else (
        "backup-restore-validation-" if args.backup_restore else ("tracing-validation-" if args.tracing else "jib-validation-"))
    output = Path(tempfile.mkdtemp(prefix=prefix, dir=output_root))
    output.chmod(0o700)
    project = output.name
    print("Evidence: " + str(output), flush=True)

    def run(command, label, **kwargs):
        with (output / (label + ".log")).open("w") as log:
            subprocess.run(command, cwd=ROOT, stdout=log, stderr=subprocess.STDOUT, check=True, **kwargs)

    if not args.skip_build:
        tasks = ["jibDockerBuild"]
        if args.tracing:
            tasks.append(":e2e:compileTestJava")
            if not args.foundation_only:
                tasks.append(":apps:payment:writeVerificationClasspath")
        run(["./gradlew", *tasks, "--no-daemon", "--console=plain", "--max-workers=2"], "images")
    elif args.tracing:
        tasks = [":e2e:compileTestJava"]
        if not args.foundation_only:
            tasks.append(":apps:payment:writeVerificationClasspath")
        run(["./gradlew", *tasks, "--offline", "--no-daemon", "--console=plain"], "tracing-classpath")
    minio_image = ensure_minio_image(ROOT)
    recovery = None
    if args.backup_restore:
        from support.backup_restore_verification import BackupRestoreVerification, ensure_client_image
        ensure_client_image(ROOT)
        recovery = BackupRestoreVerification(ROOT, output, minio_image, capture)
    offset = application_offset("verify-jib", "JIB_TEST_PORT_OFFSET", PORTS.values())
    for attempt in range(100):
        minio_port = 15000 + secrets.randbelow(3000)
        with socket.socket() as connection:
            try:
                connection.bind(("127.0.0.1", minio_port))
                break
            except OSError:
                continue
    else:
        raise RuntimeError("No isolated MinIO port available")
    public = "http://127.0.0.1:" + str(PORTS["gateway"] + offset)
    keys = {name: secrets.token_urlsafe(32) for name in ["pg-db", "payment", "settlement", "control", "catalog", "download", "store", "order-catalog"]}
    environment = os.environ.copy()
    environment.update(MOCK_PG_DB_PASSWORD=keys["pg-db"], MOCK_PG_DB_ROOT_PASSWORD=keys["pg-db"],
                       MOCK_PG_PAYMENT_KEY=keys["payment"], MOCK_PG_SETTLEMENT_KEY=keys["settlement"],
                       MOCK_PG_CONTROL_KEY=keys["control"], CATALOG_SETTLEMENT_SERVICE_KEY=keys["catalog"],
                       CATALOG_DOWNLOAD_SERVICE_KEY=keys["download"], CATALOG_STORE_SERVICE_KEY=keys["store"], CATALOG_ORDER_SERVICE_KEY=keys["order-catalog"])
    if args.prometheus_only:
        environment.update(DB_USER="stove", DB_PASSWORD="stove1234", BFF_CLIENT_SECRET=secrets.token_urlsafe(32),
                           PAYMENT_ORDER_SERVICE_KEY=secrets.token_urlsafe(32),
                           PAYMENT_APPROVAL_PAYLOAD_KEY=base64.b64encode(secrets.token_bytes(32)).decode(),
                           STORAGE_ACCESS_KEY="stove", STORAGE_SECRET_KEY="stove1234")
    compose_options = ["--env-file", "/dev/null"] if args.prometheus_only else []
    base = json.loads(capture(["docker", "compose", *compose_options, "-f", "docker-compose.apps.yml", "config", "--format", "json"], env=environment))
    schemas = [name for name in PORTS if name not in {"gateway", "download", "mock-pg"}]
    init = output / "init.sql"
    init.write_text("\n".join("CREATE DATABASE stove_" + name + "; GRANT ALL PRIVILEGES ON stove_" + name + ".* TO 'stove'@'%';" for name in schemas)
                    + ("\n" + recovery.init_sql() if recovery else ""))
    init.chmod(0o644)
    db_health = {"test": ["CMD", "mysqladmin", "ping", "-h", "127.0.0.1"], "interval": "2s", "timeout": "3s", "retries": 90}
    services = {
        "mysql": {"image": "mysql:8.0", "networks": ["app"],
                  "environment": {"MYSQL_ROOT_PASSWORD": "root1234", "MYSQL_USER": "stove", "MYSQL_PASSWORD": "stove1234"},
                  "volumes": [str(init) + ":/docker-entrypoint-initdb.d/01-schema.sql:ro"], "healthcheck": db_health},
        "pg-mysql": {"image": "mysql:8.0", "networks": ["pg"],
                     "environment": {"MYSQL_ROOT_PASSWORD": keys["pg-db"], "MYSQL_DATABASE": "mock_pg", "MYSQL_USER": "mock_pg", "MYSQL_PASSWORD": keys["pg-db"]},
                     "healthcheck": db_health},
        "redis": {"image": "redis:7-alpine", "networks": ["app"]},
        "minio": {"image": minio_image, "networks": ["app"], "ports": ["127.0.0.1:" + str(minio_port) + ":9000"],
                  "environment": {"MINIO_ROOT_USER": "stove", "MINIO_ROOT_PASSWORD": "stove1234"},
                  "command": ["server", "/data"],
                  "healthcheck": {"test": ["CMD", "mc", "ready", "local"], "interval": "2s", "timeout": "3s", "retries": 90}},
        "kafka": {"image": "apache/kafka:3.9.0", "networks": ["app"],
                  "environment": {"KAFKA_NODE_ID": "1", "KAFKA_PROCESS_ROLES": "broker,controller",
                                  "KAFKA_LISTENERS": "PLAINTEXT://:19092,CONTROLLER://:9093",
                                  "KAFKA_ADVERTISED_LISTENERS": "PLAINTEXT://kafka:19092",
                                  "KAFKA_LISTENER_SECURITY_PROTOCOL_MAP": "CONTROLLER:PLAINTEXT,PLAINTEXT:PLAINTEXT",
                                  "KAFKA_CONTROLLER_QUORUM_VOTERS": "1@kafka:9093", "KAFKA_CONTROLLER_LISTENER_NAMES": "CONTROLLER",
                                  "KAFKA_INTER_BROKER_LISTENER_NAME": "PLAINTEXT", "KAFKA_OFFSETS_TOPIC_REPLICATION_FACTOR": "1",
                                  "KAFKA_TRANSACTION_STATE_LOG_REPLICATION_FACTOR": "1", "KAFKA_TRANSACTION_STATE_LOG_MIN_ISR": "1",
                                  "KAFKA_AUTO_CREATE_TOPICS_ENABLE": "true"}}}
    for name, port in PORTS.items():
        configured = base["services"][name]
        if "build" in configured:
            raise RuntimeError("Default Compose still builds " + name)
        app_env = dict(configured["environment"])
        if args.prometheus_only:
            app_env.update(PAYMENT_PG_PROVIDER="SIMULATED", SETTLEMENT_PG_PROVIDER="SIMULATED",
                           SETTLEMENT_TOSSPAY_ENABLED="false")
        app_env.update(JWT_ISSUER_URI=public, TRACING_SAMPLE_RATE="1" if args.tracing else "0")
        if name in {"auth", "gateway"}:
            app_env.update(BFF_PUBLIC_AUTH_BASE=public, BFF_REDIRECT_URI=public + "/login/oauth2/code/gateway-bff")
        if name == "auth":
            app_env.update(AUTH_ISSUER=public, AUTH_REVIEWER_EMAIL="reviewer-check@review.local",
                           AUTH_REVIEWER_PASSWORD="reviewer-password-1234", AUTH_ADMIN_EMAIL="admin-check@review.local",
                           AUTH_ADMIN_PASSWORD="admin-password-1234")
        if name in {"studio", "review", "download"}:
            app_env.update(STORAGE_PRESIGN_ENDPOINT="http://127.0.0.1:" + str(minio_port), STORAGE_BUCKET="stove-builds")
        if name == "studio":
            app_env["STUDIO_ASSET_PUBLIC_BASE_URL"] = public
        if name == "review":
            app_env.update(REVIEW_STORAGE_ACCESS_KEY="review-reader", REVIEW_STORAGE_SECRET_KEY="isolated-read-only-password")
        if name == "download":
            app_env.update(DOWNLOAD_STORAGE_ACCESS_KEY="download-reader", DOWNLOAD_STORAGE_SECRET_KEY="isolated-read-only-password")
        services[name] = {"image": configured["image"], "environment": app_env,
                          "healthcheck": configured["healthcheck"], "stop_grace_period": configured["stop_grace_period"],
                          "ports": ["127.0.0.1:" + str(port + offset) + ":" + str(port)], "mem_limit": "768m",
                          "networks": ["app", "pg"] if name == "mock-pg" else ["app"]}
    prometheus = None
    if args.prometheus_only:
        from support.prometheus_verification import PrometheusVerification
        prometheus = PrometheusVerification(ROOT, output, services, PORTS, capture)
    tracing = None
    if args.tracing:
        from support.tracing_verification import TracingVerification
        tracing = TracingVerification(ROOT, output, services, offset, run, capture, args.foundation_only)
    compose = output / "compose.json"
    configuration = {"services": services, "networks": {"app": {}, "pg": {"internal": True}}}
    if tracing:
        configuration["volumes"] = {"tempo-data": {}}
    compose.write_text(json.dumps(configuration, indent=2))
    compose.chmod(0o600)
    docker = ["docker", "compose", "-p", project, "-f", str(compose)]
    original = []
    container_ids = capture(["docker", "ps", "-aq"]).splitlines()
    if container_ids:
        for container in json.loads(capture(["docker", "inspect", *container_ids])):
            labels = container["Config"].get("Labels") or {}
            # Parallel Testcontainers tests remove their own containers on completion.
            if not any(key.startswith("org.testcontainers") for key in labels):
                original.append(container["Id"])
    result = {"applications": {}, "phases": [], "port_offset": offset, "complete": False,
              "started_at": started_at, "host": platform.platform(), "command": sys.argv, "project": project}
    mc = docker + ["exec", "-T", "minio", "mc"]

    def provision_storage(suffix=""):
        # Bucket, read-only policy and accounts are provisioning, not data: they are recreated, not restored.
        run(mc + ["alias", "set", "admin", "http://localhost:9000", "stove", "stove1234"], "minio-alias" + suffix)
        run(mc + ["mb", "admin/stove-builds"], "minio-bucket" + suffix)
        policy = json.dumps({"Version": "2012-10-17", "Statement": [
            {"Effect": "Allow", "Action": ["s3:GetObject"], "Resource": ["arn:aws:s3:::stove-builds/*"]},
            {"Effect": "Allow", "Action": ["s3:ListBucket"], "Resource": ["arn:aws:s3:::stove-builds"]}]})
        run(docker + ["exec", "-T", "minio", "sh", "-c", "cat > /tmp/read-policy.json"], "minio-policy-file" + suffix, input=policy, text=True)
        run(mc + ["admin", "policy", "create", "admin", "build-read", "/tmp/read-policy.json"], "minio-policy" + suffix)
        for user in ["review-reader", "download-reader"]:
            run(mc + ["admin", "user", "add", "admin", user, "isolated-read-only-password"], user + "-create" + suffix)
            run(mc + ["admin", "policy", "attach", "admin", "build-read", "--user", user], user + "-policy" + suffix)
        run(mc + ["alias", "set", "reader", "http://localhost:9000", "review-reader", "isolated-read-only-password"], "minio-reader" + suffix)

    def start_applications(suffix=""):
        launcher = copy_launcher(ROOT, output)
        run(["bash", str(launcher), "-p", project, "-f", str(compose)], "start-apps" + suffix)
        # Prometheus is started by its own verification after the applications are ready.
        selected = [option for name in services if not (prometheus and name == "prometheus")
                    for option in ("--service", name)] if prometheus else []
        run([sys.executable, str(ROOT / "tools/verification/stack-status.py"),
             "-p", project, "-f", str(compose), "--timeout", "30", *selected], "stack-status" + suffix)

    try:
        run(docker + ["up", "-d", "--no-build", "--wait", "--wait-timeout", "240", "mysql", "pg-mysql", "redis", "kafka", "minio"], "infra")
        provision_storage()
        denied = subprocess.run(mc + ["pipe", "reader/stove-builds/forbidden.zip"], input=b"forbidden", stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        if denied.returncode == 0:
            raise RuntimeError("Read-only MinIO account accepted an upload")
        run(mc + ["pipe", "admin/stove-builds/iam-check.bin"], "minio-check-file", input=b"read-only fixture")
        denied = subprocess.run(mc + ["rm", "reader/stove-builds/iam-check.bin"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        if denied.returncode == 0:
            raise RuntimeError("Read-only MinIO account deleted an object")
        if tracing:
            tracing.start(docker, compose)
        start_applications()
        for name in PORTS:
            container_id = capture(docker + ["ps", "-q", name])
            info = json.loads(capture(["docker", "inspect", container_id]))[0]
            pg_credentials = {entry.split("=", 1)[0] for entry in info["Config"]["Env"] if entry.startswith("MOCK_PG_")}
            allowed = {"mock-pg": {"MOCK_PG_DB_HOST", "MOCK_PG_DB_PORT", "MOCK_PG_DB_NAME", "MOCK_PG_DB_USER", "MOCK_PG_DB_PASSWORD",
                                   "MOCK_PG_PAYMENT_KEY", "MOCK_PG_SETTLEMENT_KEY", "MOCK_PG_CONTROL_KEY"},
                       "payment": {"MOCK_PG_URI", "MOCK_PG_PAYMENT_KEY"}, "settlement": {"MOCK_PG_URI", "MOCK_PG_SETTLEMENT_KEY"}}
            if not pg_credentials.issubset(allowed.get(name, set())):
                raise RuntimeError("PG credentials exceeded application role: " + name)
            image_output = ROOT / ("simulators/mock-pg" if name == "mock-pg" else "apps/" + name) / "build"
            # Docker image stores expose either the config ID or the manifest digest.
            expected = {(image_output / filename).read_text().strip() for filename in ["jib-image.id", "jib-image.digest"]}
            if info["Image"] not in expected or info["State"]["Health"]["Status"] != "healthy" or info["RestartCount"] != 0:
                raise RuntimeError("Jib image/health mismatch for " + name)
            if capture(docker + ["exec", "-T", name, "id", "-u"]) != "100" or capture(docker + ["exec", "-T", name, "id", "-g"]) != "101":
                raise RuntimeError("Unexpected application user: " + name)
            app_timezone = "UTC" if name == "mock-pg" else "Asia/Seoul"
            command_line = capture(docker + ["exec", "-T", name, "sh", "-c", "tr '\\000' ' ' < /proc/1/cmdline"])
            if "java" not in command_line or "-Duser.timezone=" + app_timezone not in command_line or "-XX:MaxRAMPercentage=75" not in command_line:
                raise RuntimeError("JVM is not PID 1 with expected options: " + name)
            result["applications"][name] = {"image_id": info["Image"], "healthy": True, "user": "100:101", "timezone": app_timezone, "restart_count": 0}
        print("PASS: 12 Jib images, health, user, JVM options and PID 1", flush=True)

        evidence = output / "settlement.json"
        def phase(name):
            run(["./gradlew", ":e2e:settlementE2eTest", "--no-daemon", "--console=plain",
                 "-Dstove.e2e.port-offset=" + str(offset), "-Dstove.e2e.settlement-phase=" + name,
                 "-Dstove.e2e.settlement-evidence=" + str(evidence)], name)
            source = ROOT / "e2e/build/test-results/settlementE2eTest"
            copied = output / ("junit-" + name)
            shutil.copytree(source, copied)
            suites = [ET.parse(path).getroot() for path in copied.glob("TEST-*.xml")]
            if sum(int(suite.get("tests", 0)) for suite in suites) != 1 or any(int(suite.get(key, 0)) for suite in suites for key in ["failures", "errors", "skipped"]):
                raise RuntimeError("Expected one executed E2E check: " + name)
            result["phases"].append(name)
            print("PASS: " + name, flush=True)
        if prometheus:
            prometheus.verify(docker, run, result)
        elif tracing:
            tracing.verify(result, list(PORTS), keys["pg-db"])
        else:
            if recovery:
                recovery.bind(docker, run, project)
                recovery.start_copies()
                # The dump holds schemas and seed accounts; every purchase, payment, license and
                # settlement row below exists only in the streamed binlogs and the object mirror.
                recovery.full_backup()
            phase("initialPurchasesAndDownloads")
            phase("allocationAndOwnershipAreIsolated")
            if recovery:
                recovery.lose_and_restore([name for name in PORTS if name != "mock-pg"],
                                          lambda: provision_storage("-replacement"),
                                          lambda: start_applications("-after-restore"))
                result["backup_restore"] = recovery.evidence
            request = urllib.request.Request("http://127.0.0.1:" + str(PORTS["mock-pg"] + offset) + "/test-support/v1/settlement-runs",
                                             data=json.dumps({"requestId": str(uuid.uuid4())}).encode(),
                                             headers={"X-Pg-Api-Key": keys["control"], "Content-Type": "application/json"})
            with urllib.request.urlopen(request, timeout=20) as response:
                report = json.load(response)
            state = json.loads(evidence.read_text())
            state["activeReceiptId"] = report["providerSettlementId"]
            evidence.write_text(json.dumps(state))
            phase("collectsPayoutAndRetriesWithoutDuplicatingAmounts")
        run(docker + ["stop", *PORTS], "stop")
        for name in PORTS:
            container_id = capture(docker + ["ps", "-aq", name])
            state = json.loads(capture(["docker", "inspect", container_id]))[0]["State"]
            shutdown_log = capture(docker + ["logs", "--no-color", name], stderr=subprocess.STDOUT)
            if state["ExitCode"] not in {0, 143} or state["OOMKilled"] or "Graceful shutdown complete" not in shutdown_log:
                raise RuntimeError("Application did not shut down normally: " + name)
            result["applications"][name]["shutdown_exit_code"] = state["ExitCode"]
        result["normal_shutdown_count"] = len(PORTS)
        result["complete"] = True
    except BaseException as error:
        result["error"] = str(error)
        raise
    finally:
        if recovery:
            recovery.close()
        if tracing:
            subprocess.run(docker + ["unpause", "kafka"], cwd=ROOT, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        for name in [*PORTS, *(["tempo", "grafana"] if tracing else []), *(["prometheus"] if prometheus else [])]:
            with (output / (name + ".log")).open("w") as log:
                subprocess.run(docker + ["logs", "--no-color", name], cwd=ROOT, stdout=log, stderr=subprocess.STDOUT)
        run(docker + ["down", "--volumes", "--remove-orphans"], "cleanup")
        remaining = set(capture(["docker", "ps", "-aq", "--no-trunc"]).splitlines())
        missing = set(original) - remaining
        result["original_containers_preserved"] = not missing
        if missing:
            result["complete"] = False
            result["error"] = "An original container disappeared"
        if tracing or prometheus or recovery:
            try:
                (tracing or prometheus or recovery).check_preserved_volumes()
                result["original_volumes_preserved"] = True
            except RuntimeError as error:
                result["complete"] = False
                result["error"] = str(error)
                missing.add("original-volume")
        result["finished_at"] = datetime.now(timezone.utc).isoformat()
        (output / "result.json").write_text(json.dumps(result, indent=2))
        if missing:
            raise RuntimeError(result["error"])
    description = "real Prometheus collection and normal shutdown" if prometheus else (
        "MySQL/MinIO loss, restore from continuous copies, continued settlement and normal shutdown" if recovery else (
        "common Tempo/Grafana, HTTP tracing and collector/sampling checks" if args.foundation_only else (
        "durable Payment tracing, Tempo/Grafana and fault recovery" if tracing else "Jib deployment, purchase/download/settlement and normal shutdown")))
    print("PASS: " + description, flush=True)


if __name__ == "__main__":
    main()
