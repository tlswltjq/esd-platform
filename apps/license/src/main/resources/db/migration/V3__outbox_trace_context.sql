-- 분산 추적: 적재 시점의 W3C traceparent 를 이벤트와 함께 남긴다.
--
-- Kafka 자동 계측은 send() 를 호출한 스레드에 매달린 컨텍스트를 헤더에 싣는다.
-- 그런데 Outbox 는 발행을 일부러 뒤로 미루므로 실제 발행자는 요청 스레드가 아니라 릴레이 스케줄러다.
-- 자동 계측에만 맡기면 컨슈머가 "릴레이가 돈 폴링 회차"를 부모로 삼고,
-- 한 배치에 여러 애그리거트가 섞이면 무관한 주문들이 같은 traceId 를 공유한다.
--
-- 그래서 적재 시점(아직 요청 스레드다)에 붙잡아 여기 저장하고, 릴레이가 발행할 때 되살린다.
-- 이벤트 본문에 적용한 논리 -- 지금 커밋하고 나중에 보낸다 -- 를 추적 컨텍스트에도 적용하는 것이다.
--
-- 형식은 00-<32hex traceId>-<16hex spanId>-<2hex flags> 로 55자 고정이라 VARCHAR(64) 로 충분하다.
-- NULL 을 허용한다: 이 컬럼이 생기기 전에 쌓인 이벤트가 있고, 추적을 구성하지 않은 실행도 있다.
-- 릴레이는 값이 없으면 헤더를 붙이지 않고, 그 경우 컨슈머가 새 트레이스를 시작한다.
--
-- 인덱스는 만들지 않는다 -- 릴레이 조회 조건에 들어가지 않고, 사람이 traceId 로 이벤트를 찾을 때는
-- 추적 백엔드(Tempo)에서 시작하지 이 표를 스캔하지 않는다.
ALTER TABLE outbox_event ADD COLUMN trace_parent VARCHAR(64) NULL AFTER payload;
