CREATE TABLE payment_approval (
    id BIGINT NOT NULL AUTO_INCREMENT,
    approval_id VARCHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    payment_id VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
    order_no VARCHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    request_event_id VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
    buyer_subject VARCHAR(100) COLLATE utf8mb4_bin NOT NULL,
    supplier_attempt_id VARCHAR(100) COLLATE utf8mb4_bin NOT NULL,
    token_fingerprint VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    amount BIGINT NOT NULL,
    currency VARCHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    protected_payload MEDIUMTEXT NULL,
    status VARCHAR(30) NOT NULL,
    received_at DATETIME(6) NOT NULL,
    expires_at DATETIME(6) NOT NULL,
    admitted_at DATETIME(6) NULL,
    first_prepared_at DATETIME(6) NULL,
    failed_at DATETIME(6) NULL,
    resolved_at DATETIME(6) NULL,
    next_at DATETIME(6) NULL,
    lease_token VARCHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    lease_until DATETIME(6) NULL,
    post_stopped BOOLEAN NOT NULL DEFAULT FALSE,
    last_error_code VARCHAR(100) NULL,
    active_guard TINYINT GENERATED ALWAYS AS (CASE WHEN status IN ('REQUESTED','ADMITTED','REVIEW_REQUIRED','FAILURE_CONFIRMED') THEN 1 ELSE NULL END) STORED,
    PRIMARY KEY(id),
    UNIQUE KEY uk_payment_approval_id(approval_id),
    UNIQUE KEY uk_payment_approval_supplier_attempt(supplier_attempt_id),
    UNIQUE KEY uk_payment_approval_active(payment_id,active_guard),
    KEY idx_payment_approval_due(next_at,lease_until,id),
    CONSTRAINT fk_payment_approval_payment FOREIGN KEY(payment_id) REFERENCES purchase_payment(payment_id) ON DELETE CASCADE,
    CONSTRAINT chk_payment_approval_charge CHECK(amount>0 AND currency='KRW'),
    CONSTRAINT chk_payment_approval_lease CHECK((lease_token IS NULL AND lease_until IS NULL) OR (lease_token IS NOT NULL AND lease_until IS NOT NULL)),
    CONSTRAINT chk_payment_approval_window CHECK(first_prepared_at IS NULL OR admitted_at IS NOT NULL),
    CONSTRAINT chk_payment_approval_resolution CHECK(
        (status IN ('SUCCEEDED','FAILED','EXPIRED') AND resolved_at IS NOT NULL AND next_at IS NULL AND protected_payload IS NULL)
        OR (status IN ('REQUESTED','ADMITTED','REVIEW_REQUIRED','FAILURE_CONFIRMED') AND resolved_at IS NULL AND next_at IS NOT NULL AND protected_payload IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
