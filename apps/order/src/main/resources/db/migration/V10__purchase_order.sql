CREATE TABLE purchase_order (
    id BIGINT NOT NULL AUTO_INCREMENT,
    order_no VARCHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    buyer_subject VARCHAR(100) COLLATE utf8mb4_bin NOT NULL,
    request_id VARCHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    product_id BIGINT NOT NULL,
    product_code VARCHAR(50) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    title VARCHAR(200) NOT NULL,
    content_version BIGINT NOT NULL,
    list_amount BIGINT NOT NULL,
    discount_amount BIGINT NOT NULL,
    amount BIGINT NOT NULL,
    currency VARCHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    status VARCHAR(20) NOT NULL,
    request_event_id VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
    payment_result_event_id VARCHAR(64) COLLATE utf8mb4_bin NULL,
    payment_id VARCHAR(64) COLLATE utf8mb4_bin NULL,
    result_occurred_at DATETIME(6) NULL,
    failure_reason_code VARCHAR(100) NULL,
    failure_reason VARCHAR(500) NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_purchase_order_no (order_no),
    UNIQUE KEY uk_purchase_order_request (buyer_subject, request_id),
    UNIQUE KEY uk_purchase_order_event (request_event_id),
    UNIQUE KEY uk_purchase_order_result (payment_result_event_id),
    KEY idx_purchase_order_buyer (buyer_subject, created_at, id),
    CONSTRAINT chk_purchase_order_price CHECK (list_amount > 0 AND discount_amount >= 0
        AND amount > 0 AND amount = list_amount - discount_amount)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
